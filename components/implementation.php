    <h2>How to Implement IT Financial Management</h2>

    <div class="steps">

      <article class="step">
        <span>01</span>
        <h3>Establish Cost Visibility</h3>
        <p>
          Bring together financial, operational and technology
          consumption data.
        </p>
      </article>

      <article class="step">
        <span>02</span>
        <h3>Build the Technology Cost Model</h3>
        <p>
          Define how infrastructure, applications, people and vendors
          map to technology services.
        </p>
      </article>

      <article class="step">
        <span>03</span>
        <h3>Define Allocation Rules</h3>
        <p>
          Determine how shared costs should be distributed across
          consuming business units and services.
        </p>
      </article>

      <article class="step">
        <span>04</span>
        <h3>Connect Costs to Business Consumption</h3>
        <p>
          Relate technology spending to the teams, products and
          services using it.
        </p>
      </article>

      <article class="step">
        <span>05</span>
        <h3>Introduce Planning and Forecasting</h3>
        <p>
          Use the financial model to improve technology budgets and
          future spending decisions.
        </p>
      </article>

      <article class="step">
        <span>06</span>
        <h3>Improve Continuously</h3>
        <p>
          Use cost transparency and consumption data to identify
          opportunities for optimization.
        </p>
      </article>

    </div>

