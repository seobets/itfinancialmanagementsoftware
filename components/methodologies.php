    <h2>IT Financial Management Methodologies</h2>

    <p class="section-intro">
      ITFM often overlaps with several financial and technology
      management disciplines. Understanding the differences helps
      organizations choose the right operating model.
    </p>

    <div class="cards">

      <article class="card">
        <h3>IT Financial Management</h3>
        <p>
          ITFM focuses on budgeting, forecasting, allocation,
          cost transparency and financial management of technology.
        </p>
      </article>

      <article class="card">
        <h3>Technology Business Management</h3>
        <p>
          TBM connects technology costs and consumption with business
          services, capabilities and value.
        </p>
      </article>

      <article class="card">
        <h3>FinOps</h3>
        <p>
          FinOps focuses on financial accountability and optimization
          of variable cloud and technology consumption.
        </p>
      </article>

      <article class="card">
        <h3>Technology Cost Management</h3>
        <p>
          Technology Cost Management focuses on modelling, understanding
          and controlling the cost of technology across the enterprise.
        </p>
      </article>

    </div>

